#!/usr/bin/env python3
"""Compose in-call lock OSD sprites from the incoming-call lock button.

Rebuilds closed / open from the designed 来电 lock button:

  - 140x140 circle, fill #000000, radius 70 (incoming_call_init.c)
  - 72x72 icon, no scale
    closed: lock_closed_72_copy_72x72_RGB565A8_NONE
    open:   ic_lock_open_72_72x72_RGB565A8_NONE

The 72x72 assets are not optically centered in their own canvas, and the
incoming-call LVGL placement (13,21) sits high-left in the 140 circle. For
the in-call OSD the glyph alpha-mass centroid is aligned to the circle
center so the lock sits in the middle of the button.

The bitmap sits on a 144x144 canvas (2px transparent pad) so the ARGB8888
stride stays 576 bytes (64-byte aligned for the GPU overlay).
"""
from __future__ import annotations

import math
import re
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent
GEN = ROOT.parent / "beken_generated"
OUT_C = ROOT / "lock_osd_icon.c"
CLOSED_C = GEN / "image" / "lock_closed_72_copy_72x72_RGB565A8_NONE.c"
OPEN_C = GEN / "image" / "ic_lock_open_72_72x72_RGB565A8_NONE.c"

CANVAS = 144
BTN = 140
PAD = (CANVAS - BTN) // 2  # 2
ICON_W = 72
ICON_H = 72
BLACK = (0x00, 0x00, 0x00)


def parse_lvgl_rgb565a8(path: Path, w: int, h: int) -> tuple[Image.Image, float, float]:
    txt = path.read_text()
    m = re.search(r"uint8_t\s+\w+_map\[\]\s*=\s*\{(.*?)\};", txt, re.S)
    if m is None:
        raise SystemExit(f"no byte map in {path}")
    raw = bytes(int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{1,2})", m.group(1)))
    rgb_size = w * h * 2
    a_size = w * h
    if len(raw) < rgb_size + a_size:
        raise SystemExit(f"{path}: got {len(raw)} bytes, need {rgb_size + a_size}")
    rgb = raw[:rgb_size]
    alpha = raw[rgb_size:rgb_size + a_size]
    img = Image.new("RGBA", (w, h))
    px = img.load()
    mass = cx_m = cy_m = 0.0
    for y in range(h):
        for x in range(w):
            i = (y * w + x) * 2
            c = rgb[i] | (rgb[i + 1] << 8)  # little-endian RGB565
            r = ((c >> 11) & 0x1F) * 255 // 31
            g = ((c >> 5) & 0x3F) * 255 // 63
            b = (c & 0x1F) * 255 // 31
            a = alpha[y * w + x]
            px[x, y] = (r, g, b, a)
            if a >= 16:
                mass += a
                cx_m += (x + 0.5) * a
                cy_m += (y + 0.5) * a
    if mass <= 0.0:
        raise SystemExit(f"{path}: icon has no opaque pixels")
    return img, cx_m / mass, cy_m / mass


def draw_circle_aa(canvas: Image.Image) -> None:
    """Coverage-AA disk matching LVGL's 1px fringe (no 4x downsample)."""
    cx = cy = PAD + BTN / 2.0
    radius = BTN / 2.0
    px = canvas.load()
    for y in range(CANVAS):
        for x in range(CANVAS):
            d = math.hypot(x + 0.5 - cx, y + 0.5 - cy)
            cov = max(0.0, min(1.0, radius - d + 0.5))
            if cov > 0.0:
                px[x, y] = (BLACK[0], BLACK[1], BLACK[2], int(round(cov * 255.0)))


def compose(icon: Image.Image, cent_cx: float, cent_cy: float) -> tuple[Image.Image, int, int]:
    circle_cx = circle_cy = PAD + BTN / 2.0
    ox = int(round(circle_cx - cent_cx))
    oy = int(round(circle_cy - cent_cy))
    canvas = Image.new("RGBA", (CANVAS, CANVAS), (0, 0, 0, 0))
    draw_circle_aa(canvas)
    canvas.alpha_composite(icon, (ox, oy))
    return canvas, ox, oy


def pixels_argb8888(img: Image.Image) -> list[int]:
    px = img.load()
    out: list[int] = []
    for y in range(CANVAS):
        for x in range(CANVAS):
            r, g, b, a = px[x, y]
            out.append((a << 24) | (r << 16) | (g << 8) | b)
    return out


def emit_array(name: str, values: list[int]) -> list[str]:
    lines = [f"const uint32_t {name}[{CANVAS * CANVAS}] = {{\n"]
    for i in range(0, len(values), 8):
        lines.append("    " + ", ".join("0x%08X" % v for v in values[i:i + 8]) + ",\n")
    lines.append("};\n")
    return lines


def main() -> None:
    closed_icon, closed_cx, closed_cy = parse_lvgl_rgb565a8(CLOSED_C, ICON_W, ICON_H)
    open_icon, open_cx, open_cy = parse_lvgl_rgb565a8(OPEN_C, ICON_W, ICON_H)
    closed, cox, coy = compose(closed_icon, closed_cx, closed_cy)
    opened, oox, ooy = compose(open_icon, open_cx, open_cy)
    closed.save(ROOT / "lock_osd_closed_preview.png")
    opened.save(ROOT / "lock_osd_open_preview.png")

    lines = [
        "/* AUTO-GENERATED by lock_osd_icon_gen.py - in-call lock OSD icons.\n",
        f" * {CANVAS}x{CANVAS} ARGB8888, uint32 = (A<<24)|(R<<16)|(G<<8)|B (BGRA byte order).\n",
        " * Source: incoming-call lock button (140x140 #000000 circle +\n",
        f" * 72x72 icon, alpha-centroid centered on the circle).\n",
        f" * closed icon @ ({cox},{coy}), open icon @ ({oox},{ooy}). */\n",
        "#include <stdint.h>\n\n",
    ]
    lines.extend(emit_array("g_lock_closed_icon_argb8888", pixels_argb8888(closed)))
    lines.append("\n")
    lines.extend(emit_array("g_lock_open_icon_argb8888", pixels_argb8888(opened)))
    OUT_C.write_text("".join(lines))
    print(
        f"wrote {OUT_C} ({CANVAS}x{CANVAS}, "
        f"closed @ {cox},{coy} cent={closed_cx:.1f},{closed_cy:.1f}; "
        f"open @ {oox},{ooy} cent={open_cx:.1f},{open_cy:.1f})"
    )


if __name__ == "__main__":
    main()
