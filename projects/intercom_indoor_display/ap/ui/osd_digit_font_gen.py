#!/usr/bin/env python3
"""Generate 8-bit alpha glyphs for the in-call duration OSD (0-9 and ':').

WeChat-style timer sits on the video as white digits. LVGL is torn down during
the call, so the compositor blits a pre-rasterized ARGB8888 strip; this script
only packs the glyphs used to paint that strip at runtime.
"""
from __future__ import annotations

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent
OUT_C = ROOT / "osd_digit_font.c"
OUT_H = ROOT / "osd_digit_font.h"
FONT_PATH = Path("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf")
FONT_PX = 44
CHARS = "0123456789:"
PAD_X = 1
PAD_Y = 4


def main() -> None:
    font = ImageFont.truetype(str(FONT_PATH), FONT_PX)
    glyphs: list[tuple[str, int, int, bytes]] = []
    max_h = 0
    for ch in CHARS:
        bbox = font.getbbox(ch)
        gw = max(1, bbox[2] - bbox[0])
        gh = max(1, bbox[3] - bbox[1])
        img = Image.new("L", (gw + PAD_X * 2, gh + PAD_Y * 2), 0)
        draw = ImageDraw.Draw(img)
        draw.text((PAD_X - bbox[0], PAD_Y - bbox[1]), ch, font=font, fill=255)
        # Tight-crop empty columns but keep a 1px gutter.
        px = img.load()
        min_x, max_x = img.width, -1
        min_y, max_y = img.height, -1
        for y in range(img.height):
            for x in range(img.width):
                if px[x, y] > 8:
                    min_x = min(min_x, x)
                    max_x = max(max_x, x)
                    min_y = min(min_y, y)
                    max_y = max(max_y, y)
        if max_x < min_x:
            crop = Image.new("L", (8, FONT_PX), 0)
        else:
            crop = img.crop((min_x, min_y, max_x + 1, max_y + 1))
        advance = max(crop.width + 2, font.getlength(ch).__ceil__())
        glyphs.append((ch, crop.width, advance, crop.tobytes()))
        max_h = max(max_h, crop.height)

    lines_h = [
        "/* AUTO-GENERATED by osd_digit_font_gen.py - in-call duration glyphs. */\n",
        "#ifndef __OSD_DIGIT_FONT_H__\n",
        "#define __OSD_DIGIT_FONT_H__\n\n",
        "#include <stdint.h>\n\n",
        f"#define OSD_DIGIT_H  ({max_h})\n",
        f"#define OSD_DIGIT_N  ({len(CHARS)})\n\n",
        "typedef struct {\n",
        "    uint8_t w;\n",
        "    uint8_t advance;\n",
        "    const uint8_t *alpha; /* w * OSD_DIGIT_H, row-major */\n",
        "} osd_digit_glyph_t;\n\n",
        "extern const osd_digit_glyph_t g_osd_digits[OSD_DIGIT_N];\n\n",
        "#endif\n",
    ]
    OUT_H.write_text("".join(lines_h))

    lines_c = [
        "/* AUTO-GENERATED by osd_digit_font_gen.py - DejaVu Sans "
        f"{FONT_PX}px, 8-bit alpha. */\n",
        "#include \"osd_digit_font.h\"\n\n",
    ]
    for i, (ch, w, _adv, raw) in enumerate(glyphs):
        # Pad glyph height to OSD_DIGIT_H (top-align).
        padded = bytearray(w * max_h)
        src_h = len(raw) // w
        top = (max_h - src_h) // 2
        padded[top * w : top * w + w * src_h] = raw
        name = f"s_osd_digit_{i}"
        lines_c.append(f"/* '{ch}' {w}x{max_h} */\n")
        lines_c.append(f"static const uint8_t {name}[{w * max_h}] = {{\n")
        for row in range(0, len(padded), 16):
            chunk = padded[row : row + 16]
            lines_c.append("    " + ", ".join(f"0x{b:02X}" for b in chunk) + ",\n")
        lines_c.append("};\n\n")

    lines_c.append("const osd_digit_glyph_t g_osd_digits[OSD_DIGIT_N] = {\n")
    for i, (ch, w, adv, _raw) in enumerate(glyphs):
        lines_c.append(
            f"    {{ {w}, {adv}, s_osd_digit_{i} }}, /* '{ch}' */\n"
        )
    lines_c.append("};\n")
    OUT_C.write_text("".join(lines_c))
    print(f"wrote {OUT_H.name} / {OUT_C.name} glyph_h={max_h}")
    for ch, w, adv, _ in glyphs:
        print(f"  '{ch}' w={w} adv={adv}")


if __name__ == "__main__":
    main()
